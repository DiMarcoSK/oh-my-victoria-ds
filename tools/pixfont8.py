# i sem pingo (base p/ í ï ī)
g('ı',2,"# # # # #")
# ponto embaixo (vietnamita / iorubá)
DOTBELOW = {'ẹ':'e','ọ':'o','Ọ':'O','ệ':('e','circ')}

def _pad(rows, w):
    return [r.ljust(w, '.') for r in rows]

def _compose(base, acc):
    top, rows = G[base]
    w = max(len(r) for r in rows)
    a = ACC[acc]
    aw = max(len(r) for r in a)
    if aw > w:   # acento mais largo que a letra (i): alarga a celula
        off = (aw - w) // 2
        rows = ['.' * off + r + '.' * (aw - w - off) for r in rows]
        w = aw
    ax = (w - aw + 1) // 2
    arows = ['.' * ax + r.ljust(aw, '.') + '.' * (w - aw - ax) for r in a]
    if top >= 2:      # minuscula: acento nas linhas 0-1 (ancorado em cima da letra)
        atop = top - len(arows)
        return (atop, arows + rows)
    atop = top - len(arows)   # maiuscula: linhas -2/-1 (cabe na linha de 11px)
    return (atop, arows + rows)

for ch, (b, a) in COMPOSE.items():
    G[ch] = _compose(b, a)
for ch, b in DOTBELOW.items():
    top, rows = _compose(*b) if isinstance(b, tuple) else G[b]
    w = max(len(r) for r in rows)
    rows = list(rows)
    while top + len(rows) < 8:
        rows.append('.' * w)
    rows.append('.' * ((w - 1) // 2) + '#' + '.' * (w - 1 - (w - 1) // 2))
    G[ch] = (top, rows)
# cedilha (Ç ç): gancho abaixo da letra
for ch, b in (('Ç', 'C'), ('ç', 'c')):
    top, rows = G[b]
    w = max(len(r) for r in rows)
    m = (w - 1) // 2
    G[ch] = (top, list(rows) + ['.' * m + '#' + '.' * (w - m - 1), '.' * (m - 1) + '##' + '.' * (w - m - 1)])
# ơ ư: chifre a direita
G['ơ'] = (1, ["....#", ".##.#", "#..#.", "#..#.", "#..#.", ".##.."])
G['ư'] = (1, [".....#", "#..#.#", "#..##.", "#..#..", "#..#..", ".###.."])
# marcas combinantes (avanco 0, desenhadas sobre a letra anterior)
COMBINING = {0x300: ACC['grave'], 0x301: ACC['acute'], 0x303: ACC['tilde']}

def glyphs():
    """Lista de (cp, adv, w, h, left, top_rel_baseline, bitsrows) p/ o genfont.
    top_rel_baseline segue a convencao do Glyph: linhas acima da baseline."""
    out = {}
    for ch, (top, rows) in G.items():
        w = max(len(r) for r in rows)
        rows = _pad(rows, w)
        # corta colunas vazias a esquerda/direita mantendo o avanco
        out[ord(ch)] = dict(w=w, h=len(rows), left=0, top=7 - top, adv=w + 1,
                            rows=rows)
    out[32] = dict(w=0, h=0, left=0, top=0, adv=3, rows=[])
    for cp, rows in COMBINING.items():
        w = max(len(r) for r in rows)
        out[cp] = dict(w=w, h=len(rows), left=-(w + 3), top=7, adv=0, rows=rows)
    return out
